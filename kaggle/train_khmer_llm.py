def self_test(rt: Runtime):
    print("\n[🧪] Self-test (tiny model, synthetic data)...")
    t0 = time.time()
    rt = replace(rt, ddp=False)
    cfg = tiny_config()
    torch.manual_seed(0)
    check_newton_schulz(rt)
    model = KimiMoELM(cfg).to(rt.device)
