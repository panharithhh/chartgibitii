RELATIVE_IMPORT = re.compile(r"^(\s*)from \.[\w.]* import ")


def strip_relative_imports(source: str) -> str:
    """Drops package-internal imports (everything lives in one namespace in the bundle)."""
    out, skipping = [], False
    for line in source.splitlines():
        if skipping:
            skipping = ")" not in line
            continue
        m = RELATIVE_IMPORT.match(line)
        if m:
            if m.group(1):
                out.append(m.group(1) + "pass")   # keeps an indented block non-empty
            skipping = "(" in line and ")" not in line
            continue
        out.append(line)
    return "\n".join(out)


def top_level_names(source: str):
    names = []
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)):
            names.append(node.name)
        elif isinstance(node, ast.Assign):
            names += [t.id for t in node.targets if isinstance(t, ast.Name)]
    return names


def build() -> str:
    parts, owner = [HEADER], {}
    for rel in MODULES:
        source = strip_relative_imports((PKG / rel).read_text(encoding="utf-8"))
        for name in top_level_names(source):
            if name in owner and name not in ("__all__",):
                raise SystemExit(f"name clash in bundle: {name} defined in {owner[name]} and {rel}")
            owner[name] = rel
        parts.append(f"\n\n# {'=' * 86}\n# khmer_llm/{rel}\n# {'=' * 86}\n{source.strip()}\n")
    bundle = "".join(parts) + FOOTER
    ast.parse(bundle)   # must be valid Python
    return bundle


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed bundle is out of date")
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args()
    bundle = build()
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != bundle:
            print(f"{out} is stale: run python scripts/build_kaggle_script.py")
            sys.exit(1)
        print(f"{out} is up to date")
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(bundle, encoding="utf-8")
    print(f"wrote {out} ({len(bundle.splitlines())} lines)")


if __name__ == "__main__":
    main()
